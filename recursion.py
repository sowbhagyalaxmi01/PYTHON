#Recursion is a programming technique where a function calls itself to solve a smaller version of the same problem.

# Two important parts of recursion

# ① Base Case
#  Tells the function when to stop.
# ② Recursive Case
#  The function calls itself with a smaller/simpler problem.


#Why recursion is used
# Recursion is useful when a problem can be broken into smaller problems of the same type.
# Common examples:
# Trees
# Graphs
# Backtracking
# Divide and conquer
# Factorial
# Fibonacci

